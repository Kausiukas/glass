// Builds everything that is generated in this package:
//   dist/relief.worker.js      worker script (classic; also works as a module worker)
//   dist/glass-slab.esm.js     engine as an ES module (bundlers, <script type="module">)
//   dist/glass-slab.iife.js    engine as a classic script, global `GlassSlabLib` (works from file://)
//   carved-glass-lab.html      the tuning lab, one self-contained page (double-click to open)
//   test/overlay.js            overlay-mode test page bundle
// Optional: node build.mjs --artifact <file>  also writes the lab as a fragment for a Claude artifact.
import * as esbuild from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

mkdirSync("dist", { recursive: true });

// 1) worker; also exported as a string so the single-file lab can start it as a blob: worker
const worker = await esbuild.build({ entryPoints: ["src/glass/relief.worker.ts"], bundle: true, format: "iife", minify: true, write: false, target: "es2020" });
const workerCode = worker.outputFiles[0].text;
writeFileSync("dist/relief.worker.js", workerCode);
writeFileSync("lab/worker-src.generated.ts", `// generated by build.mjs (do not edit)\nconst src: string = ${JSON.stringify(workerCode)};\nexport default src;\n`);

// 2) engine builds
await esbuild.build({ entryPoints: ["src/glass/index.ts"], bundle: true, format: "esm", target: "es2020", outfile: "dist/glass-slab.esm.js", legalComments: "inline" });
await esbuild.build({ entryPoints: ["src/glass/index.ts"], bundle: true, format: "iife", globalName: "GlassSlabLib", target: "es2020", outfile: "dist/glass-slab.iife.js", legalComments: "inline" });

// 3) the lab: template + inlined glass.css + bundled lab.ts
const lab = await esbuild.build({ entryPoints: ["lab/lab.ts"], bundle: true, format: "iife", minify: true, write: false, target: "es2020" });
const js = lab.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const css = readFileSync("src/glass/glass.css", "utf8");
let page = readFileSync("lab/lab.template.html", "utf8");
const swap = (from, to) => { if (!page.includes(from)) throw new Error(`lab.template.html is missing ${from}`); page = page.replace(from, () => to); };
swap(`<link rel="stylesheet" href="../src/glass/glass.css" data-build-inline>`, `<style>\n${css}</style>`);
swap("<!--lab-script-->", `<script>\n${js}\n</script>`);
page = page.replace(/<!--template-notice-->[\s\S]*?<!--\/template-notice-->\n?/, "");
page = page.replace(/<!-- Template for [^>]*-->\n/, "<!-- Generated by build.mjs from lab/lab.template.html and lab/lab.ts. Edit those, then run npm run build. -->\n");
writeFileSync("carved-glass-lab.html", page);

// optional artifact fragment (the Claude artifact host supplies doctype/html/head/body itself)
const ai = process.argv.indexOf("--artifact");
if (ai > 0 && process.argv[ai + 1]) {
  const head = page.slice(page.indexOf("<head>") + 6, page.indexOf("</head>"))
    .replace(/<meta charset[^>]*>\n?/, "").replace(/<meta name="viewport"[^>]*>\n?/, "");
  const body = page.slice(page.indexOf("<body>") + 6, page.lastIndexOf("</body>"));
  writeFileSync(process.argv[ai + 1], `${head.trim()}\n${body.trim()}\n`);
}

// 4) overlay-mode test page bundle
await esbuild.build({ entryPoints: ["test/overlay.ts"], bundle: true, format: "iife", target: "es2020", outfile: "test/overlay.js" });

console.log(`worker ${workerCode.length} B · lab js ${js.length} B · lab page ${page.length} B`);
